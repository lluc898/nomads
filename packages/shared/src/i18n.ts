export const supportedLocales = [
  { code: "es", label: "Español" },
  { code: "en", label: "English" },
  { code: "ca", label: "Català" },
  { code: "fr", label: "Français" },
  { code: "de", label: "Deutsch" },
  { code: "it", label: "Italiano" },
  { code: "pt", label: "Português" },
  { code: "nl", label: "Nederlands" },
] as const;

export type SupportedLocale = (typeof supportedLocales)[number]["code"];

const localeCodes = new Set<string>(supportedLocales.map(({ code }) => code));

export function isSupportedLocale(value: unknown): value is SupportedLocale {
  return typeof value === "string" && localeCodes.has(value);
}

export function localeForCountry(countryCode?: string | null): SupportedLocale {
  const country = countryCode?.toUpperCase();
  if (country === "ES") return "es";
  if (country === "AD") return "ca";
  if (["FR", "MC", "LU"].includes(country ?? "")) return "fr";
  if (["DE", "AT", "CH", "LI"].includes(country ?? "")) return "de";
  if (["IT", "SM", "VA"].includes(country ?? "")) return "it";
  if (["PT", "BR", "AO", "MZ", "CV"].includes(country ?? "")) return "pt";
  if (["NL", "BE", "SR"].includes(country ?? "")) return "nl";
  return "en";
}

export function localeFromLanguageHeader(
  value?: string | null,
): SupportedLocale {
  if (!value) return "en";
  for (const part of value.split(",")) {
    const code = part.trim().split(";")[0]?.split("-")[0]?.toLowerCase();
    if (isSupportedLocale(code)) return code;
  }
  return "en";
}

